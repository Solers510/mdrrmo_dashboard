def _pdf_table(
    headers: list[str],
    rows: list[list[Any]],
    *,
    column_widths: list[float] | None = None,
    font_size: float = 6.5,
) -> Table:
    if column_widths is None:
        usable_width = landscape(A4)[0] - (20 * mm)
        column_widths = [
            usable_width / len(headers)
            for _ in headers
        ]

    header_style = ParagraphStyle(
        "ReportTableHeader",
        fontName="Helvetica-Bold",
        fontSize=font_size,
        leading=font_size + 1.5,
    )
    cell_style = ParagraphStyle(
        "ReportTableCell",
        fontName="Helvetica",
        fontSize=font_size,
        leading=font_size + 1.5,
    )

    data = [
        [
            Paragraph(escape(_safe(value)), header_style)
            for value in headers
        ]
    ]
    data.extend(
        [
            [
                Paragraph(escape(_safe(value)), cell_style)
                for value in row
            ]
            for row in rows
        ]
    )

    table = Table(
        data,
        colWidths=column_widths,
        repeatRows=1,
        hAlign="LEFT",
    )
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.lightgrey),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("GRID", (0, 0), (-1, -1), 0.25, colors.grey),
                ("LEFTPADDING", (0, 0), (-1, -1), 2),
                ("RIGHTPADDING", (0, 0), (-1, -1), 2),
                ("TOPPADDING", (0, 0), (-1, -1), 2),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
            ]
        )
    )
    return table


