class ExportServiceError(Exception):
    """Raised when a saved report snapshot cannot be exported."""


def _snapshot(record: dict[str, object]) -> dict[str, object]:
    snapshot = record.get("snapshot_json")

    if not isinstance(snapshot, dict):
        raise ExportServiceError(
            "The selected report snapshot is invalid."
        )

    return snapshot


def _safe(value: Any) -> str:
    if value is None:
        return ""
    return str(value)


def _display_event_name(event: dict[str, object]) -> str:
    classification = _safe(
        event.get("classification")
    ).strip()
    name = _safe(
        event.get("event_name")
    ).strip()

    if classification:
        return f"{classification} {name}".strip()

    return name or "Disaster Event"


def report_filename(
    record: dict[str, object],
    *,
    extension: str,
) -> str:
    snapshot = _snapshot(record)
    event = snapshot.get("event") or {}
    event_name = _display_event_name(event)
    sitrep = _safe(
        record.get("sitrep_number")
    ).strip() or "Snapshot"
    mode = _safe(
        record.get("report_mode")
    )
    snapshot_id = int(
        record["id"]
    )

    raw = (
        f"MDRRMO_Naic_{event_name}_{sitrep}_{mode}_"
        f"snapshot_{snapshot_id}.{extension}"
    )

    return re.sub(
        r"[^A-Za-z0-9._-]+",
        "_",
        raw,
    ).strip("_")


def _write_table_sheet(
    workbook: Workbook,
    *,
    title: str,
    headers: list[str],
    rows: list[list[Any]],
) -> None:
    sheet = workbook.create_sheet(
        title=title
    )
    sheet.freeze_panes = "A2"
    sheet.append(headers)

    for row in rows:
        sheet.append(row)

    for cell in sheet[1]:
        cell.font = Font(bold=True)
        cell.alignment = Alignment(
            horizontal="center",
            vertical="center",
            wrap_text=True,
        )

    for row in sheet.iter_rows(
        min_row=2
    ):
        for cell in row:
            cell.alignment = Alignment(
                vertical="top",
                wrap_text=True,
            )

    for column_index, header in enumerate(
        headers,
        start=1,
    ):
        values = [
            _safe(header)
        ]
        values.extend(
            _safe(
                sheet.cell(
                    row=row_number,
                    column=column_index,
                ).value
            )
            for row_number in range(
                2,
                sheet.max_row + 1,
            )
        )

        width = min(
            max(
                max(
                    (len(value) for value in values),
                    default=10,
                ) + 2,
                10,
            ),
            36,
        )

        sheet.column_dimensions[
            get_column_letter(column_index)
        ].width = width

    sheet.auto_filter.ref = sheet.dimensions


